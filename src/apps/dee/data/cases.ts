function shuffleOptions<T>(items: T[], seed: string): T[] {
  const result = [...items];
  const seedValue = Number(seed) || 1;

  for (let index = result.length - 1; index > 0; index -= 1) {
    const swapIndex = (seedValue + index * 2) % (index + 1);
    [result[index], result[swapIndex]] = [result[swapIndex], result[index]];
  }

  return result;
}

function buildCase(seed: CaseSeed): DetectiveCase {
  const truthOptions = shuffleOptions([
    { id: 'truth', label: conclusionFor(seed.category) },
    ...decoysFor(seed.category).map((label, index) => ({ id: `decoy-${index + 1}`, label })),
  ], seed.id);

  return {
    id: seed.id,
    title: seed.title,
    subtitle: seed.subtitle,
    difficulty: seed.difficulty,
    category: seed.category,
    sourceFile: seed.sourceFile,
    intro: seed.intro,
    readerNote: seed.readerNote,
    playerTask: seed.task,
    imageSlots: [
      {
        id: 'scene-01',
        label: '现场图',
        futurePath: `/images/episode-${seed.id}-scene-01.png`,
        prompt: seed.imagePrompt,
      },
    ],
    investigationActions: actionsFrom(seed.clues),
    questions: [
      {
        id: 'truth',
        prompt: '你认为本案真相是什么？',
        placeholder: '写下你的判断，例如：这是伪装自尽/真正目标是旧窑场……',
      },
      {
        id: 'evidence',
        prompt: '请写出支撑你判断的三条线索。',
        placeholder: '线索一、线索二、线索三……',
      },
      {
        id: 'misdirection',
        prompt: '本案最容易误导玩家的表象是什么？',
        placeholder: '例如：看起来像自杀、看起来像普通抢劫……',
      },
    ],
    deduction: {
      truthQuestion: '先别急着看答案：你认为本案最合理的推理方向是？',
      truthOptions,
      correctTruthId: 'truth',
      evidencePrompt: '再勾选能支撑这个方向的线索。',
      notePrompt: '可选：用一句话说明你为什么排除其他可能。',
    },
    hints: {
      light: seed.hintLight,
      strong: seed.hintStrong,
    },
    solution: {
      truth: seed.truth,
      reasoning: seed.reasoning,
      scoreRubric: [
        '真相判断正确：4 分',
        '勾选关键线索：每条 1 分，最多 4 分',
        '调查至少三处线索：1 分',
        '补充一句话推理：1 分',
        '使用提示会相应扣分',
      ],
      takeaway: seed.takeaway,
    },
  };
}

