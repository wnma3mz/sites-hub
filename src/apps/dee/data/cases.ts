function actionsFrom(clues: string[]) {
  const titles = ['勘查现场', '盘问证人', '核对物证', '复查时间与路线', '追问反常点'];
  return clues.slice(0, 5).map((clue, index) => ({
    id: String.fromCharCode(65 + index),
    title: titles[index] ?? `调查线索 ${index + 1}`,
    clue,
  }));
}

